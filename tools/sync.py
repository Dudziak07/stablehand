"""Copy shared material into each platform folder.

Sources of truth:
  shared/references/*.md  -> platform reference copies
  tools/lint.py           -> platforms/<p>/skills/validating-artifacts/scripts/lint.py

Placement per platform comes from tools/sync.json:
  "root"      -> platforms/<p>/references/<file>            (all shared files)
  "per-skill" -> platforms/<p>/skills/<id>/references/<file> (files listed in contracts/skills/<id>.md)

Only platforms that already have a skills/ folder are touched. Generated files start
with a marker; never edit them by hand.

Usage:
  uv run tools/sync.py           write/refresh copies, delete stale generated files
  uv run tools/sync.py --check   exit 1 if anything is missing, different or stale (CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SHARED = ROOT / "shared" / "references"
CONTRACTS = ROOT / "contracts" / "skills"
LINT = ROOT / "tools" / "lint.py"
MARKER = "GENERATED by tools/sync.py"
PLATFORM_CARDS = ("claude-code.md", "antigravity.md", "opencode.md")


def md_copy(source: Path) -> str:
    rel = source.relative_to(ROOT).as_posix()
    header = f"<!-- {MARKER} from {rel}; edit the source, then run: uv run tools/sync.py -->\n"
    return header + source.read_text(encoding="utf-8-sig").replace("\r\n", "\n")


def py_copy(source: Path) -> str:
    rel = source.relative_to(ROOT).as_posix()
    lines = source.read_text(encoding="utf-8-sig").replace("\r\n", "\n").split("\n")
    # Keep the PEP 723 block first so `uv run` still finds the inline dependencies.
    end = lines.index("# ///", 1) + 1 if lines and lines[0] == "# /// script" else 0
    note = f"# {MARKER} from {rel}; edit the source, then run: uv run tools/sync.py"
    return "\n".join(lines[:end] + [note] + lines[end:])


def contract_references(skill_id: str, platform: str) -> list[str]:
    path = CONTRACTS / f"{skill_id}.md"
    if not path.is_file():
        return []
    text = path.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    front = yaml.safe_load(text.split("---\n", 2)[1]) if text.startswith("---\n") else None
    refs = (front.get("references") if isinstance(front, dict) else None) or []
    files: list[str] = []
    for ref in refs:
        if ref == "@platform":
            files.append(f"{platform}.md")
        elif ref == "@all-platforms":
            files.extend(PLATFORM_CARDS)
        else:
            files.append(ref)
    return list(dict.fromkeys(files))


def expected_files(platform: str, mode: str) -> dict[Path, str]:
    pdir = ROOT / "platforms" / platform
    skills = pdir / "skills"
    out: dict[Path, str] = {}
    if mode == "root":
        for src in sorted(SHARED.glob("*.md")):
            out[pdir / "references" / src.name] = md_copy(src)
    elif mode == "per-skill":
        for skill in sorted(p for p in skills.iterdir() if p.is_dir()):
            for name in contract_references(skill.name, platform):
                src = SHARED / name
                if not src.is_file():
                    sys.exit(f"contracts/skills/{skill.name}.md references missing shared file: {name}")
                out[skill / "references" / name] = md_copy(src)
    else:
        sys.exit(f"tools/sync.json: unknown references mode '{mode}' for {platform}")
    validator = skills / "validating-artifacts"
    if validator.is_dir():
        out[validator / "scripts" / "lint.py"] = py_copy(LINT)
    return out


def skills_without_contract(platform: str) -> list[str]:
    skills = ROOT / "platforms" / platform / "skills"
    return [p.relative_to(ROOT).as_posix() for p in sorted(skills.iterdir())
            if p.is_dir() and not (CONTRACTS / f"{p.name}.md").is_file()]


def generated_files(platform: str) -> set[Path]:
    pdir = ROOT / "platforms" / platform
    found = set()
    for path in list(pdir.glob("references/*.md")) + list(pdir.glob("skills/*/references/*.md")) + list(pdir.glob("skills/*/scripts/lint.py")):
        head = path.read_text(encoding="utf-8-sig", errors="replace")[:400]
        if MARKER in head:
            found.add(path)
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description="Sync shared references and the linter into platform folders.")
    parser.add_argument("--check", action="store_true", help="report drift instead of writing; exit 1 on drift")
    args = parser.parse_args()

    config = json.loads((ROOT / "tools" / "sync.json").read_text(encoding="utf-8"))
    problems: list[str] = []
    for platform, settings in config["platforms"].items():
        if not (ROOT / "platforms" / platform / "skills").is_dir():
            print(f"skip {platform}: no skills/ folder yet")
            continue
        for rel in skills_without_contract(platform):
            if args.check:
                problems.append(f"no contract for skill: {rel}")
            else:
                print(f"warning: no contract for skill {rel} (expected contracts/skills/<id>.md)")
        expected = expected_files(platform, settings["references"])
        for path, content in expected.items():
            current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else None
            if current == content:
                continue
            rel = path.relative_to(ROOT).as_posix()
            if args.check:
                problems.append(f"{'missing' if current is None else 'out of date'}: {rel}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
                print(f"wrote {rel}")
        for stale in sorted(generated_files(platform) - set(expected)):
            rel = stale.relative_to(ROOT).as_posix()
            if args.check:
                problems.append(f"stale generated file: {rel}")
            else:
                stale.unlink()
                print(f"removed {rel}")

    if problems:
        print("\n".join(problems))
        print("Run: uv run tools/sync.py")
        return 1
    print("sync: up to date" if args.check else "sync: done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
